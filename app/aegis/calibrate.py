import argparse
import datetime
import json
import logging
import math
import signal
import time

from kubernetes import client
from kubernetes.client.rest import ApiException

from aegis.calibration import environment_fingerprint, read_calibration, write_calibration
from aegis.collector import PrometheusCollector
from aegis.config import load_config
from aegis.kube import load_kubernetes_credentials

logger = logging.getLogger(__name__)

# Short windows (10s) so a step change shows up quickly
QUERY_P95 = 'histogram_quantile(0.95, sum(rate(http_request_duration_seconds_bucket{route="/"}[10s])) by (le))'
QUERY_RPS = 'sum(rate(http_request_duration_seconds_count{route="/"}[10s]))'
QUERY_ERRORS = ('sum(rate(http_request_duration_seconds_count{route="/",status_code!~"2.."}[10s]))'
                ' / sum(rate(http_request_duration_seconds_count{route="/"}[10s]))')
SAMPLE_SECONDS = 5
METRIC_LAG_SECONDS = 5      # a change in traffic shows up in Prometheus about this much later
WINDOW_SECONDS = 10         # window of the queries above
SHORTFALL_RATIO = 0.9       # served req/s below 90% of the sent req/s = the pod cannot keep up
IDLE_RPS = 0.5              # above this, someone else is sending traffic
WAIT_SINGLE_REPLICA_SECONDS = 600
WAIT_RECOVERY_SECONDS = 300
WAIT_STARTUP_SECONDS = 180

K6_SCRIPT = "\n".join([
    "import http from 'k6/http';",
    "",
    "// Generated by app/aegis/calibrate.py: constant-rate steps, one connection per request",
    "// (same traffic shape as kubernetes/k6-ramp-demo).",
    "export const options = OPTIONS;",
    "",
    "export default function () {",
    "  http.get('TARGET_URL');",
    "}",
    "",
])


def utc_text(timestamp):
    return datetime.datetime.fromtimestamp(timestamp, datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def build_steps(settings):
    steps = []
    rps = settings["start_rps"]
    while rps <= settings["max_rps"]:
        steps.append(rps)
        rps += settings["step_rps"]
    return steps


# One ramping-arrival-rate scenario: jump to each step in 1 s, then hold it.
def build_k6_options(steps, step_seconds):
    stages = []
    for rps in steps:
        stages.append({"target": rps, "duration": "1s"})
        stages.append({"target": rps, "duration": str(step_seconds - 1) + "s"})
    return {
        "noConnectionReuse": True,
        "scenarios": {
            "calibration": {
                "executor": "ramping-arrival-rate",
                "startRate": steps[0],
                "timeUnit": "1s",
                "preAllocatedVUs": 50,
                "maxVUs": 300,
                "stages": stages,
            },
        },
    }


class Calibrator:
    def __init__(self, config):
        self.config = config
        self.settings = config["calibration"]
        self.degradation = config["degradation"]
        kubernetes = config["kubernetes"]
        self.namespace = kubernetes["namespace"]
        self.hpa_name = kubernetes["hpa_name"]
        self.deployment_name = kubernetes["deployment_name"]
        self.prometheus = PrometheusCollector.from_config(config)
        self.query_ready = config["prometheus"]["query_replicas_ready"]
        self.autoscaling = client.AutoscalingV2Api()
        self.apps = client.AppsV1Api()
        self.core = client.CoreV1Api()
        self.batch = client.BatchV1Api()
        self.original_limits = None

    def query(self, text):
        return self.prometheus.query_scalar(text, time.time())

    # --- HPA ---------------------------------------------------------------

    def read_hpa_limits(self):
        hpa = self.autoscaling.read_namespaced_horizontal_pod_autoscaler(self.hpa_name, self.namespace)
        min_replicas = hpa.spec.min_replicas
        if min_replicas is None:
            min_replicas = 1
        return min_replicas, hpa.spec.max_replicas

    def set_hpa_limits(self, min_replicas, max_replicas):
        body = {"spec": {"minReplicas": min_replicas, "maxReplicas": max_replicas}}
        self.autoscaling.patch_namespaced_horizontal_pod_autoscaler(self.hpa_name, self.namespace, body)
        logger.info("HPA %s: minReplicas=%s maxReplicas=%s", self.hpa_name, min_replicas, max_replicas)

    def restore_hpa(self):
        if self.original_limits is None:
            return
        try:
            self.set_hpa_limits(self.original_limits[0], self.original_limits[1])
        except Exception as error:
            logger.error("Could not restore the HPA, set it back by hand to minReplicas=%s maxReplicas=%s: %s",
                         self.original_limits[0], self.original_limits[1], error)

    # --- Pods --------------------------------------------------------------

    def pod_selector(self):
        deployment = self.apps.read_namespaced_deployment(self.deployment_name, self.namespace)
        parts = []
        for key, value in deployment.spec.selector.match_labels.items():
            parts.append(key + "=" + value)
        return ",".join(parts)

    def ready_pods(self, selector):
        ready = {}
        for pod in self.core.list_namespaced_pod(self.namespace, label_selector=selector).items:
            if pod.metadata.deletion_timestamp is not None:
                continue
            for condition in pod.status.conditions or []:
                if condition.type == "Ready" and condition.status == "True":
                    ready[pod.metadata.name] = pod
        return ready

    def wait_single_replica(self):
        logger.info("Waiting until the deployment runs exactly 1 Ready pod")
        deadline = time.monotonic() + WAIT_SINGLE_REPLICA_SECONDS
        selector = self.pod_selector()
        while time.monotonic() < deadline:
            pods = self.core.list_namespaced_pod(self.namespace, label_selector=selector).items
            if len(pods) == 1 and len(self.ready_pods(selector)) == 1:
                return
            time.sleep(SAMPLE_SECONDS)
        raise RuntimeError("the deployment did not go down to 1 Ready pod in time")

    # --- Load Job ----------------------------------------------------------

    def script_config_map_name(self):
        return self.settings["load_job_name"] + "-script"

    def delete_load_job(self):
        name = self.settings["load_job_name"]
        try:
            self.batch.delete_namespaced_job(name, self.namespace, propagation_policy="Background")
        except ApiException as error:
            if error.status != 404:
                raise
        # Wait until its pods are gone, so the traffic has really stopped
        deadline = time.monotonic() + 120
        while time.monotonic() < deadline:
            pods = self.core.list_namespaced_pod(self.namespace, label_selector="job-name=" + name).items
            if not pods:
                return
            time.sleep(2)

    def start_load_job(self, steps):
        name = self.settings["load_job_name"]
        options = build_k6_options(steps, self.settings["step_seconds"])
        script = K6_SCRIPT.replace("OPTIONS", json.dumps(options, indent=2))
        script = script.replace("TARGET_URL", self.settings["target_url"])

        config_map = {
            "apiVersion": "v1",
            "kind": "ConfigMap",
            "metadata": {"name": self.script_config_map_name()},
            "data": {"test.js": script},
        }
        try:
            self.core.replace_namespaced_config_map(self.script_config_map_name(), self.namespace, config_map)
        except ApiException as error:
            if error.status != 404:
                raise
            self.core.create_namespaced_config_map(self.namespace, config_map)

        job = {
            "apiVersion": "batch/v1",
            "kind": "Job",
            "metadata": {"name": name, "labels": {"app.kubernetes.io/part-of": "aegis"}},
            "spec": {
                "backoffLimit": 0,
                "template": {
                    "spec": {
                        "restartPolicy": "Never",
                        "containers": [{
                            "name": "k6",
                            "image": self.settings["k6_image"],
                            "imagePullPolicy": "IfNotPresent",
                            "args": ["run", "/scripts/test.js"],
                            "volumeMounts": [{"name": "script", "mountPath": "/scripts"}],
                        }],
                        "volumes": [{"name": "script", "configMap": {"name": self.script_config_map_name()}}],
                    },
                },
            },
        }
        self.batch.create_namespaced_job(self.namespace, job)

        # The steps are timed from when the k6 container starts
        deadline = time.monotonic() + 180
        while time.monotonic() < deadline:
            for pod in self.core.list_namespaced_pod(self.namespace, label_selector="job-name=" + name).items:
                for status in pod.status.container_statuses or []:
                    if status.state.running is not None:
                        return status.state.running.started_at.timestamp()
                    if status.state.waiting is not None and status.state.waiting.reason in ("ErrImagePull", "ImagePullBackOff"):
                        raise RuntimeError("the k6 pod cannot pull " + self.settings["k6_image"])
            time.sleep(1)
        raise RuntimeError("the k6 pod did not start in time")

    def load_job_finished(self):
        try:
            job = self.batch.read_namespaced_job(self.settings["load_job_name"], self.namespace)
        except ApiException:
            return True
        if job.status.succeeded or job.status.failed:
            return True
        return False

    # --- Capacity ----------------------------------------------------------

    def wait_recovery(self):
        logger.info("Waiting for the service to recover")
        deadline = time.monotonic() + WAIT_RECOVERY_SECONDS
        while time.monotonic() < deadline:
            rps = self.query(QUERY_RPS)
            ready = self.query(self.query_ready)
            if ready is not None and ready >= 1 and (rps is None or rps < IDLE_RPS):
                break
            time.sleep(SAMPLE_SECONDS)
        cooldown = self.settings["cooldown_seconds"]
        logger.info("Cooldown %s s", cooldown)
        time.sleep(cooldown)

    def check_idle(self):
        rps = self.query(QUERY_RPS)
        if rps is not None and rps >= IDLE_RPS:
            raise RuntimeError("the service is already receiving " + str(round(rps, 1))
                               + " req/s. Stop other load (k6 Jobs) before calibrating")

    # Runs the step load once and returns the result of this run.
    def measure_capacity_once(self, steps):
        step_seconds = self.settings["step_seconds"]
        threshold = self.degradation["p95_threshold_seconds"]
        bad_samples_needed = max(1, math.ceil(self.degradation["sustained_seconds"] / SAMPLE_SECONDS))
        max_errors = self.settings["max_error_ratio"]

        stats = []
        for rps in steps:
            stats.append({"target_rps": rps, "measured_rps": [], "p95_max_s": None, "error_ratio_max": 0.0})

        self.delete_load_job()
        started_at = self.start_load_job(steps)
        logger.info("k6 started at %s: %s steps of %s s, from %s to %s req/s",
                    utc_text(started_at), len(steps), step_seconds, steps[0], steps[-1])

        bad_samples = 0
        first_bad_time = None
        result = {"started_at": utc_text(started_at), "capacity_rps": None, "reason": ""}
        try:
            while True:
                time.sleep(SAMPLE_SECONDS)
                now = time.time()
                index = int((now - started_at) // step_seconds)
                if index >= len(steps) or self.load_job_finished():
                    result["reason"] = "no degradation up to " + str(steps[-1]) + " req/s: raise calibration.max_rps"
                    break

                p95 = self.query(QUERY_P95)
                rps = self.query(QUERY_RPS)
                errors = self.query(QUERY_ERRORS)
                ready = self.query(self.query_ready)

                # Statistics of the step the metrics belong to (they arrive METRIC_LAG_SECONDS late).
                # Measured req/s only once the 10s query window is fully inside the step.
                lagged_elapsed = now - METRIC_LAG_SECONDS - started_at
                lagged_index = int(lagged_elapsed // step_seconds)
                window_inside_step = lagged_elapsed % step_seconds >= WINDOW_SECONDS
                if 0 <= lagged_index < len(stats):
                    step = stats[lagged_index]
                    if rps is not None and window_inside_step:
                        step["measured_rps"].append(rps)
                    if p95 is not None and (step["p95_max_s"] is None or p95 > step["p95_max_s"]):
                        step["p95_max_s"] = p95
                    if errors is not None and errors > step["error_ratio_max"]:
                        step["error_ratio_max"] = errors

                logger.info("step %s/%s target=%s req/s: rps=%s p95=%s errors=%s ready=%s",
                            index + 1, len(steps), steps[index], round_or_dash(rps), round_or_dash(p95, 3),
                            round_or_dash(errors, 3), round_or_dash(ready, 0))

                # Rate the pod should be serving: the current step once the query window is inside it,
                # otherwise the previous step (the window still mixes both)
                expected_rps = None
                if 0 <= lagged_index < len(steps):
                    if window_inside_step:
                        expected_rps = steps[lagged_index]
                    elif lagged_index > 0:
                        expected_rps = steps[lagged_index - 1]

                # The service only times requests it has started to handle. When it is saturated,
                # requests wait outside and P95 can still look fine: a served rate below the sent
                # rate is the sign of that.
                reason = ""
                if ready is not None and ready < 1:
                    reason = "no Ready pod (failing its readiness probe)"
                    bad_samples = bad_samples_needed
                elif expected_rps is not None and rps is not None and rps < SHORTFALL_RATIO * expected_rps:
                    reason = ("served req/s below " + str(int(SHORTFALL_RATIO * 100)) + "% of the sent req/s for "
                              + str(self.degradation["sustained_seconds"]) + " s")
                elif p95 is not None and p95 > threshold:
                    reason = "P95 above " + str(threshold) + " s for " + str(self.degradation["sustained_seconds"]) + " s"
                elif errors is not None and errors > max_errors:
                    reason = "error ratio above " + str(max_errors) + " for " + str(self.degradation["sustained_seconds"]) + " s"

                if reason == "":
                    bad_samples = 0
                    first_bad_time = None
                    continue
                if first_bad_time is None:
                    first_bad_time = now
                bad_samples += 1
                if bad_samples < bad_samples_needed:
                    continue

                # Degraded: the step that broke it is the one running when it started (minus the metric lag)
                broken_index = int((first_bad_time - METRIC_LAG_SECONDS - started_at) // step_seconds)
                broken_index = max(0, min(broken_index, len(steps) - 1))
                result["degraded_at"] = utc_text(first_bad_time)
                result["degraded_step_rps"] = steps[broken_index]
                if broken_index == 0:
                    result["reason"] = reason + " already in the first step: lower calibration.start_rps"
                else:
                    result["capacity_rps"] = steps[broken_index - 1]
                    result["reason"] = reason + " at " + str(steps[broken_index]) + " req/s"
                break
        finally:
            self.delete_load_job()

        result["ended_at"] = utc_text(time.time())
        steps_done = []
        for step in stats:
            if not step["measured_rps"] and step["p95_max_s"] is None:
                continue
            mean_rps = None
            if step["measured_rps"]:
                mean_rps = round(sum(step["measured_rps"]) / len(step["measured_rps"]), 2)
            p95_max = None
            if step["p95_max_s"] is not None:
                p95_max = round(step["p95_max_s"], 3)
            steps_done.append({
                "target_rps": step["target_rps"],
                "measured_rps": mean_rps,
                "p95_max_s": p95_max,
                "error_ratio_max": round(step["error_ratio_max"], 4),
            })
        result["steps"] = steps_done
        logger.info("Run result: C=%s (%s)", result["capacity_rps"], result["reason"])
        return result

    # --- Startup time ------------------------------------------------------

    # Raises minReplicas and times how long each new pod takes to be Ready, measured from the
    # moment of the change: that is the delay Aegis lives with when it asks for a pod.
    def measure_startup(self, max_replicas):
        target = min(self.settings["startup_replicas"], max_replicas)
        if target < 2:
            raise RuntimeError("maxReplicas must be at least 2 to measure T")
        selector = self.pod_selector()
        existing = set(self.ready_pods(selector).keys())

        self.set_hpa_limits(target, max_replicas)
        requested_at = time.time()
        new_ready = {}
        deadline = time.monotonic() + WAIT_STARTUP_SECONDS
        while time.monotonic() < deadline and len(new_ready) < target - len(existing):
            for name, pod in self.ready_pods(selector).items():
                if name in existing or name in new_ready:
                    continue
                created = pod.metadata.creation_timestamp.timestamp()
                new_ready[name] = {
                    "pod": name,
                    "request_to_ready_s": round(time.time() - requested_at, 1),
                    "created_to_ready_s": round(time.time() - created, 1),
                }
                logger.info("Pod %s Ready %s s after the request", name, new_ready[name]["request_to_ready_s"])
            time.sleep(1)

        if len(new_ready) < target - len(existing):
            raise RuntimeError("new pods were not Ready after " + str(WAIT_STARTUP_SECONDS) + " s")
        measurements = []
        for name in sorted(new_ready):
            measurements.append(new_ready[name])
        return measurements


def raise_keyboard_interrupt(signum, frame):
    raise KeyboardInterrupt


def round_or_dash(value, decimals=2):
    if value is None:
        return "-"
    return round(value, decimals)


def run(config, repetitions, skip_startup, output):
    settings = config["calibration"]
    kubernetes = config["kubernetes"]
    calibrator = Calibrator(config)
    steps = build_steps(settings)
    previous = read_calibration(settings["configmap_name"], kubernetes["namespace"])
    if skip_startup and previous is None:
        raise RuntimeError("--skip-startup needs a previous calibration to reuse its T")

    calibrator.check_idle()
    calibrator.original_limits = calibrator.read_hpa_limits()
    original_min, original_max = calibrator.original_limits
    started = time.time()

    capacity_runs = []
    startup = []
    try:
        # Capacity of one pod: pin the HPA to exactly 1 replica
        calibrator.set_hpa_limits(1, 1)
        calibrator.wait_single_replica()
        for repetition in range(repetitions):
            logger.info("Capacity run %s of %s", repetition + 1, repetitions)
            if repetition > 0:
                calibrator.wait_recovery()
            capacity_runs.append(calibrator.measure_capacity_once(steps))

        if not skip_startup:
            calibrator.wait_recovery()
            calibrator.set_hpa_limits(1, original_max)
            startup = calibrator.measure_startup(original_max)
    finally:
        calibrator.restore_hpa()

    capacities = []
    for result in capacity_runs:
        if result["capacity_rps"] is None:
            raise RuntimeError("a capacity run failed (" + result["reason"] + "), nothing was saved")
        capacities.append(result["capacity_rps"])
    capacity = min(capacities)

    if skip_startup:
        startup_time = previous["startup_time_seconds"]
        startup = previous.get("startup_measurements", [])
    else:
        slowest = 0.0
        for measurement in startup:
            if measurement["request_to_ready_s"] > slowest:
                slowest = measurement["request_to_ready_s"]
        startup_time = math.ceil(slowest)

    finished = time.time()
    calibration = {
        "capacity_rps": capacity,
        "startup_time_seconds": startup_time,
        "measured_at": utc_text(finished),
        "measured_at_unix": finished,
        "started_at": utc_text(started),
        "environment": environment_fingerprint(kubernetes["deployment_name"], kubernetes["namespace"]),
        "degradation": config["degradation"],
        "load": {
            "traffic": "k6 ramping-arrival-rate, one connection per request",
            "start_rps": settings["start_rps"],
            "step_rps": settings["step_rps"],
            "step_seconds": settings["step_seconds"],
            "target_url": settings["target_url"],
        },
        "capacity_runs": capacity_runs,
        "startup_measurements": startup,
        "hpa_restored_to": {"minReplicas": original_min, "maxReplicas": original_max},
    }
    write_calibration(settings["configmap_name"], kubernetes["namespace"], calibration)
    logger.info("Saved in ConfigMap %s/%s: C=%s req/s (runs: %s), T=%s s",
                kubernetes["namespace"], settings["configmap_name"], capacity, capacities, startup_time)

    if output:
        with open(output, "w") as f:
            json.dump(calibration, f, indent=2)
        logger.info("Copy saved to %s", output)


def main():
    parser = argparse.ArgumentParser(description="Measure C (capacity of one pod) and T (startup time) automatically")
    parser.add_argument("--repetitions", type=int, help="capacity runs; C is the lowest (default: config)")
    parser.add_argument("--skip-startup", action="store_true", help="keep T from the previous calibration")
    parser.add_argument("--output", help="also save the full result as a JSON file")
    args = parser.parse_args()

    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(message)s")
    config = load_config()
    load_kubernetes_credentials()
    repetitions = args.repetitions
    if repetitions is None:
        repetitions = config["calibration"]["repetitions"]

    # Stopping it (Ctrl+C or SIGTERM, e.g. when it runs in a pod) still restores the HPA and stops the load
    signal.signal(signal.SIGTERM, raise_keyboard_interrupt)

    logger.info("Calibrating. Aegis must NOT be running: this pins the HPA to 1 replica for a while.")
    try:
        run(config, repetitions, args.skip_startup, args.output)
    except KeyboardInterrupt:
        logger.warning("Calibration interrupted: HPA restored and load stopped, nothing was saved")
    except RuntimeError as error:
        logger.error("Calibration failed: %s", error)


if __name__ == "__main__":
    main()
